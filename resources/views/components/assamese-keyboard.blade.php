    $(document).ready(function() {
        $(".hindi-keypad table tr td a").bind("click", function(e) {
            e.stopPropagation();
            var idname = $("#overlayDiv").attr("data-value");
            var key = $(this).attr("data-value");
            e.preventDefault();
            var inputField = $("#" + idname);
            var prev_text = inputField.val();
            var cursorPos = inputField[0].selectionStart;

            if (typeof key !== "undefined") {
                if (key === "clear") {
                    inputField.val("").trigger("change");
                } else if (key === "backspace") {
                    if (cursorPos > 0) {
                        inputField.val(prev_text.substring(0, cursorPos - 1) + prev_text.substring(
                            cursorPos));
                        cursorPos--;
                    }
                    inputField.trigger("change");
                } else {
                    if (prev_text.length < 3000) {
                        inputField.val(prev_text.substring(0, cursorPos) + key + prev_text.substring(
                            cursorPos));
                        cursorPos += key.length;
                        inputField.trigger("change");
                    }
                }
                inputField[0].selectionStart = inputField[0].selectionEnd = cursorPos;
            } else {
                alert("Unable to fill search box!");
            }
        });
    });




    function showKeyboard(id) {
        // Triggering a click event might not be necessary if you're already binding a click handler
        // $("#" + id).trigger('click');

        // Bind a click event handler to the input field
// Get the id of the clicked input field
        $("#overlayDiv").show(); // Show the overlay
        $("#overlayDiv").attr("data-value", id); // Set the data-value attribute to the input field's id

    }



    $('#close').click(function() {
        $("#overlayDiv").hide();
    });

