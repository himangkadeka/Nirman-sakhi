                <li>The above timelines will remain same after the applicant has updated the application as per the
                    observations mentioned in the revert message.</li>
                <li>The above timelines are for new registrations. Timelines for processing onboarding applications
                    of registered workers is twice the timeline specified for new registrations.</li>
                <li>The data (Name, DoB, permanent address and applicant photo) in the Aadhaar will be the final
                    data, particularly in cases of mismatch of the existing data of already registered workers.</li>
                <li>RO shall replace the previous data (data on BOCW ID card) with the Aadhaar data in case the
                    name or DoB (either one) is different from Aadhaar data but the other is matching with
                    Aadhaar. However, RO shall ensure that the other documents are in order and the details on
