$(document).ready(function() {

    $('#ageproof').focus(function() {
        $(this).addClass('custom-focus-border');
    });

    $('#ageproof').blur(function() {
        $(this).removeClass('custom-focus-border');
    });

    $('#certificateproof').focus(function() {
        $(this).addClass('custom-focus-border');
    });

    $('#certificateproof').blur(function() {
        $(this).removeClass('custom-focus-border');
    });
    



});
